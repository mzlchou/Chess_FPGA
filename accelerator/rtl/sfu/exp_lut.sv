// =============================================================================
// exp_lut.sv
// Look-up table for exponential function exp(-delta * S) used in Softmax.
// Owner:   Hoang
// Latency: 1 clock cycle (synchronous read)
//
// Numerical Specifications (from gen_exp_lut.py):
// - Centered attention score dynamic range: ~496.0
// - Scale factor: S = 496.0 / 32768.0 = 0.01513671875 per LSB
// - Input:  delta = (x_max - x) >= 0 (integer difference code)
// - Output: Q0.16 unsigned fixed-point (0xFFFF = 1.0, 0x0000 = 0.0)
// - Size:   512 entries x 16 bits = 1024 bytes (1 KB)
// - Table maps: index k in [0, 511] -> round(exp(-k * S) * 65535)
// - Clipping: delta >= 512 clips to 0 (exp(-512*S) <= 0.00043 < 29/65535)
// =============================================================================
`timescale 1ns / 1ps

module exp_lut #(
  parameter int    DEPTH     = 512,          // Number of LUT entries
  parameter int    DATA_W    = 16,           // Output width: Q0.16 fixed point
  parameter int    DELTA_W   = 16,           // Input delta width
  parameter string INIT_FILE = "exp_lut.mem" // Initialization memory file
) (
  input  logic               clk,
  input  logic               rst_n,

  input  logic               en,             // 1 = perform lookup
  input  logic [DELTA_W-1:0] delta,          // Difference code: (x_max - x) >= 0

  output logic [DATA_W-1:0]  val_out,        // Q0.16 exponential value: exp(-delta * S)
  output logic               valid_out       // 1 = valid output (1 clock cycle latency)
);

  localparam int ADDR_W = $clog2(DEPTH);     // 9 address bits for 512 entries

  // 512 x 16-bit ROM array (1 KB)
  // Inferred as Block RAM (RAMB18E2) or distributed ROM in Vivado
  (* rom_style = "block" *)
  logic [DATA_W-1:0] lut [0:DEPTH-1];

  // Initialize ROM from .mem file generated by gen_exp_lut.py
  initial begin
    $readmemh(INIT_FILE, lut);
  end

  // Synchronous read with out-of-bounds clipping (1 cycle latency)
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      val_out   <= '0;
      valid_out <= 1'b0;
    end else begin
      valid_out <= en;
      if (en) begin
        // If delta is within [0, 511], return table value.
        // If delta >= 512, exp(-delta * S) is negligible (< 0.00043), safely clip to 0.
        if (delta < DEPTH) begin
          val_out <= lut[delta[ADDR_W-1:0]];
        end else begin
          val_out <= '0;
        end
      end
    end
  end

endmodule

